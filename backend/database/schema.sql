CREATE DATABASE IF NOT EXISTS relay_chat CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE relay_chat;
CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  profile_image VARCHAR(500) NULL,
  is_online TINYINT(1) NOT NULL DEFAULT 0,
  last_seen DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_users_online (is_online)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chats (
  id VARCHAR(40) NOT NULL PRIMARY KEY,
  chat_type ENUM('individual','group') NOT NULL DEFAULT 'individual',
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_chats_creator FOREIGN KEY (created_by) REFERENCES users(id),
  INDEX idx_chats_activity (updated_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chat_members (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  chat_id VARCHAR(40) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  joined_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uq_chat_member (chat_id,user_id),
  INDEX idx_member_user (user_id,is_active),
  CONSTRAINT fk_member_chat FOREIGN KEY (chat_id) REFERENCES chats(id) ON DELETE CASCADE,
  CONSTRAINT fk_member_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chat_settings (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  chat_id VARCHAR(40) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  is_muted TINYINT(1) NOT NULL DEFAULT 0,
  is_archived TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_chat_setting (chat_id,user_id),
  CONSTRAINT fk_setting_chat FOREIGN KEY (chat_id) REFERENCES chats(id) ON DELETE CASCADE,
  CONSTRAINT fk_setting_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
